/**
 * THE CHANGELOG, BUILT FOR THE GAME AND THE PAGE.
 *
 *   bun tools/build-changelog.ts           write both files
 *   bun tools/build-changelog.ts --check   exit 1 if either is stale (pre-push)
 *
 * Reads src/changelog/entries.ts and writes:
 *   godot/assets/changelog.json      WHAT'S NEW and the version tag (changelog.gd)
 *   landing/changelog/index.html     rabbit.rip/changelog/, served as is by nginx
 *
 * Both are committed, like the i18n JSON: the Docker build has no bun, and a
 * fresh Godot checkout needs none. The pre-commit hook regenerates them when
 * the source is staged, so they cannot drift.
 *
 * THE PAGE speaks the five languages. It is written in English (what a crawler
 * and a no-script browser see) with every language embedded as JSON; a few
 * lines of script re-render it in `?lang=` (the game passes its own) or the
 * browser's language. `#v1.4` frames that version as "Your version".
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

import { CHANGELOG, CHANGELOG_UI, versionAt, type Release } from '../src/changelog/entries';
import { LOCALES } from '../src/i18n/locales';

const ROOT = join((import.meta as ImportMeta & { dir: string }).dir, '..');
const GAME_OUT = join(ROOT, 'godot', 'assets', 'changelog.json');
const PAGE_OUT = join(ROOT, 'landing', 'changelog', 'index.html');

const KINDS = ['new', 'tune', 'fix'] as const;

/** Everything the compiler cannot see: order, dates, blanks. */
function validate(releases: Release[]): string[] {
  const errors: string[] = [];
  if (releases.length === 0) errors.push('no release at all');
  let previous = '9999-99-99';
  releases.forEach((r, i) => {
    const where = `${versionAt(i)} (${r.date})`;
    if (!/^\d{4}-\d{2}-\d{2}$/.test(r.date) || Number.isNaN(Date.parse(r.date))) {
      errors.push(`${where}: date must be YYYY-MM-DD`);
    }
    if (r.date > previous) errors.push(`${where}: newer than the entry above it — newest first`);
    previous = r.date;
    if (r.items.length === 0) errors.push(`${where}: no item`);
    r.items.forEach((item, j) => {
      if (!KINDS.includes(item.kind)) errors.push(`${where} item ${j + 1}: unknown kind "${item.kind}"`);
      for (const locale of LOCALES) {
        const text = item.text[locale];
        if (typeof text !== 'string' || text.trim() === '') {
          errors.push(`${where} item ${j + 1}: missing ${locale}`);
        } else if (text !== text.trim()) {
          errors.push(`${where} item ${j + 1}: ${locale} has stray spaces`);
        }
      }
    });
  });
  return errors;
}

function gameJson(): string {
  const releases = CHANGELOG.map((r, i) => ({ version: versionAt(i), date: r.date, items: r.items }));
  return `${JSON.stringify({ ui: CHANGELOG_UI, releases }, null, 2)}\n`;
}

function esc(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function englishDate(iso: string): string {
  return new Date(`${iso}T12:00:00Z`).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    timeZone: 'UTC',
  });
}

function releaseHtml(r: Release, i: number): string {
  const ui = CHANGELOG_UI.en;
  const version = versionAt(i);
  const items = r.items
    .filter((item) => !item.web2)
    .map((item) => `<li><span class="chip ${item.kind}">${esc(ui.kinds[item.kind])}</span><span>${esc(item.text.en)}</span></li>`)
    .join('\n          ');
  return `      <article class="release" id="${version}">
        <header>
          <h2>${version}</h2>
          <time datetime="${r.date}">${englishDate(r.date)}</time>
          <span class="you">${esc(ui.yourVersion)}</span>
        </header>
        <ul>
          ${items}
        </ul>
      </article>`;
}

