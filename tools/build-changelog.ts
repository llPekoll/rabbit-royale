const errors = validate(CHANGELOG);
if (errors.length > 0) {
  console.error(`changelog: ${errors.length} problem(s) in src/changelog/entries.ts`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}

const outputs: [string, string][] = [
  [GAME_OUT, gameJson()],
  [PAGE_OUT, pageHtml()],
];

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([path, text]) => {
    try {
      return readFileSync(path, 'utf8') !== text;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    console.error('changelog: generated files are stale — run `bun tools/build-changelog.ts`');
    for (const [path] of stale) console.error(`  - ${path.slice(ROOT.length + 1)}`);
    process.exit(1);
  }
  console.log(`changelog: up to date (${versionAt(0)})`);
} else {
  for (const [path, text] of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
  console.log(`changelog: ${versionAt(0)} — wrote ${outputs.map(([p]) => p.slice(ROOT.length + 1)).join(', ')}`);
}
